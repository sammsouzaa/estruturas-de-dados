#include <iostream>
#include <string>
using namespace std;

int main(){
  int meuInt = 5;
  float meuFloat = 3.14;
  double meuDouble = 6.28;
  char meuChar = 'F';
  bool meuBool = 8;
  string minhaString = "Texto";

  cout << "Inteiro: " << meuInt << "\n"; 
  cout << "Real(float): " << meuFloat << "\n"; 
  cout << "Real(double): " << meuDouble << "\n"; 
  cout << "Caractere: " << meuChar << "\n"; 
  cout << "Logico: " << meuBool << "\n"; 
  cout << "String: " << minhaString << "\n"; 
  
  return 0;
}
